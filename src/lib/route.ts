export function route(href: string): string {
  if (!href) return '/';
  const m = /^([A-Za-z0-9]+)\.dc\.html(#.*)?$/.exec(href);
  if (!m) return href;
  return (map[m[1]] ?? '/') + (m[2] ?? '');
}
